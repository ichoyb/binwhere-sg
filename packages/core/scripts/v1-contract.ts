/**
 * Freeze the public v1 API contract.
 *
 * An installed app version outlives every web deploy, so the shape of
 * `/api/v1/*` is a promise the server cannot take back. This script renders
 * the shared Zod schemas to JSON Schema and compares the result with the
 * committed snapshot in `contracts/v1.json`:
 *
 *   --check   exit 1 if the schemas no longer match the snapshot (default)
 *   --update  rewrite the snapshot; review the resulting `git diff` — every
 *             changed line is a change installed clients will see
 *
 * A change is compatible only if it is additive on responses (new optional
 * fields) or loosening on requests. Anything else needs a new API version.
 *
 * Run from a package that has `tsx` (both app/ and mobile/ do):
 *   tsx ../packages/core/scripts/v1-contract.ts --check
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { z } from 'zod';
import {
  API_V1_PATHS,
  ApiErrorResponseSchema,
  ClassifyRequestSchema,
  ClassifyResultSchema,
  NearbyQuerySchema,
  NearbyResponseSchema,
} from '../src';

const SNAPSHOT_PATH = join(__dirname, '..', 'contracts', 'v1.json');

/**
 * Everything is rendered from the "input" side: a request as the server
 * accepts it, a response as the client receives it. Transforms and refinements
 * run after parsing and are not part of the wire shape, so they are allowed to
 * be unrepresentable.
 */
function render(schema: z.ZodType): unknown {
  return z.toJSONSchema(schema, {
    target: 'draft-2020-12',
    io: 'input',
    unrepresentable: 'any',
  });
}

function buildContract() {
  return {
    $comment:
      'Generated by packages/core/scripts/v1-contract.ts — do not edit by hand. '
      + 'Update with `tsx ../packages/core/scripts/v1-contract.ts --update` and review the diff.',
    version: 'v1',
    paths: API_V1_PATHS,
    schemas: {
      'classify.request': render(ClassifyRequestSchema),
      'classify.response': render(ClassifyResultSchema),
      'nearby.query': render(NearbyQuerySchema),
      'nearby.response': render(NearbyResponseSchema),
      'error': render(ApiErrorResponseSchema),
    },
  };
}

function serialize(contract: unknown): string {
  return `${JSON.stringify(contract, null, 2)}\n`;
}

function printFirstDifferences(snapshot: string, current: string): void {
  const a = snapshot.split('\n');
  const b = current.split('\n');
  const limit = Math.max(a.length, b.length);
  let shown = 0;
  for (let i = 0; i < limit && shown < 20; i++) {
    if (a[i] === b[i]) continue;
    console.error(`  line ${i + 1}`);
    console.error(`    snapshot: ${a[i] ?? '<end of file>'}`);
    console.error(`    current:  ${b[i] ?? '<end of file>'}`);
    shown++;
  }
}

function main(argv: string[]): number {
  const mode = argv.includes('--update') ? 'update' : 'check';
  const current = serialize(buildContract());

  if (mode === 'update') {
    mkdirSync(dirname(SNAPSHOT_PATH), { recursive: true });
    writeFileSync(SNAPSHOT_PATH, current);
    console.log(`v1 contract snapshot written to ${SNAPSHOT_PATH}`);
    return 0;
  }

  if (!existsSync(SNAPSHOT_PATH)) {
    console.error(`v1 contract snapshot missing at ${SNAPSHOT_PATH}; run with --update once and commit it`);
    return 1;
  }

  const snapshot = readFileSync(SNAPSHOT_PATH, 'utf8');
  if (snapshot === current) {
    console.log('PASS v1 contract matches contracts/v1.json');
    return 0;
  }

  console.error('FAIL v1 contract drifted from contracts/v1.json (first differences, line-by-line):');
  printFirstDifferences(snapshot, current);
  console.error(
    'If the change is intentional and backward compatible, run `--update` and review `git diff packages/core/contracts/v1.json`.',
  );
  return 1;
}

process.exit(main(process.argv.slice(2)));
