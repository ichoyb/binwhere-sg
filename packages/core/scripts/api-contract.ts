/**
 * Freeze v1 and v2 from the shared schemas' wire input shapes.
 * --check rejects drift; --update rewrites the selected version's snapshot.
 * A change is compatible only if it adds optional response fields or loosens
 * requests. Anything else requires a new API version.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { z } from 'zod';

interface ContractDefinition {
  version: 'v1' | 'v2';
  paths: Record<string, string>;
  schemas: Record<string, z.ZodType>;
}

function printFirstDifferences(snapshot: string, current: string): void {
  const a = snapshot.split('\n');
  const b = current.split('\n');
  const limit = Math.max(a.length, b.length);
  let shown = 0;
  for (let i = 0; i < limit && shown < 20; i++) {
    if (a[i] === b[i]) continue;
    console.error(`  line ${i + 1}`);
    console.error(`    snapshot: ${a[i] ?? '<end of file>'}`);
    console.error(`    current:  ${b[i] ?? '<end of file>'}`);
    shown++;
  }
}

export function runContract(definition: ContractDefinition, argv: string[]): number {
  const { version, paths, schemas } = definition;
  const snapshotPath = join(__dirname, '..', 'contracts', `${version}.json`);
  const mode = argv.includes('--update') ? 'update' : 'check';
  const contract = {
    $comment:
      `Generated by packages/core/scripts/${version}-contract.ts — do not edit by hand. `
      + `Update with \`tsx ../packages/core/scripts/${version}-contract.ts --update\` and review the diff.`,
    version,
    paths,
    schemas: Object.fromEntries(Object.entries(schemas).map(([name, schema]) => [
      name,
      z.toJSONSchema(schema, { target: 'draft-2020-12', io: 'input', unrepresentable: 'any' }),
    ])),
  };
  const current = `${JSON.stringify(contract, null, 2)}\n`;

  if (mode === 'update') {
    mkdirSync(dirname(snapshotPath), { recursive: true });
    writeFileSync(snapshotPath, current);
    console.log(`${version} contract snapshot written to ${snapshotPath}`);
    return 0;
  }

  if (!existsSync(snapshotPath)) {
    console.error(`${version} contract snapshot missing at ${snapshotPath}; run with --update once and commit it`);
    return 1;
  }

  const snapshot = readFileSync(snapshotPath, 'utf8');
  if (snapshot === current) {
    console.log(`PASS ${version} contract matches contracts/${version}.json`);
    return 0;
  }

  console.error(`FAIL ${version} contract drifted from contracts/${version}.json (first differences, line-by-line):`);
  printFirstDifferences(snapshot, current);
  console.error(
    `If the change is intentional and backward compatible, run \`--update\` and review \`git diff packages/core/contracts/${version}.json\`.`,
  );
  return 1;
}
